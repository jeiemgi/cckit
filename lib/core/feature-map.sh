#!/usr/bin/env bash
# feature-map.sh - print the feature map: every cckit verb, its group, its skill and the files that
# implement it. Generated from scripts/lib/verbs.tsv (the verb list) and bin/cckit (the dispatcher's
# case blocks), so it cannot drift from either (#605, decisions 45 and 55).
#
#   lib/core/feature-map.sh           print the map to stdout
#   lib/core/feature-map.sh --write   rewrite FEATURES.md
#   lib/core/feature-map.sh --check   exit 1 when FEATURES.md is stale (run by scripts/check.sh)
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/FEATURES.md"

# Helpers every verb loads; naming them on each row would hide the file that does the work.
PLUMBING='^(kit-config|kit-lib|role-identity)\.sh$'

impl_map() {
  # verb<TAB>file per dispatcher reference to $ROOT/scripts/... or $LIB/... inside the verb's block.
  perl -ne '
    if (/^  ([a-z][a-z|-]*)\)/) { $v = $1 } elsif (/^  [*]\)/) { $v = "" }
    if ($v ne "" && /(?:\$ROOT\/scripts\/|\$LIB\/)([A-Za-z0-9_.\/-]+\.sh)/) {
      for my $k (split /\|/, $v) { print "$k\t$1\n" }
    }' "$ROOT/bin/cckit" | sort -u
}

render() {
  local map; map="$(impl_map)"
  cat <<'EOF'
# Feature map

Generated by `lib/core/feature-map.sh --write`; `scripts/check.sh` fails when it is stale. Do not
edit by hand.

## Layers

| Path | Holds | Rules |
| --- | --- | --- |
| `bin/` | the `cckit` dispatcher | `bin/PROMPTS.md` |
| `lib/core/` | repo-wide checks with no forge or verb knowledge | `lib/PROMPTS.md` |
| `scripts/` | verb implementations, the gate and its tests (moving to `lib/` by ratchet) | `scripts/PROMPTS.md` |
| `kit/` | everything `cckit init` installs into a project | `kit/PROMPTS.md` |
| `docs-site/` | the documentation site and its media | `docs-site/PROMPTS.md` |

## Verbs

| Verb | Group | Skill | Implemented in (under `scripts/` or `scripts/lib/`) |
| --- | --- | --- | --- |
EOF
  awk -F'\t' '$2=="group"{g=$1} $2=="verb"||$2=="default"{print $1"\t"g"\t"$6}' "$ROOT/scripts/lib/verbs.tsv" |
    while IFS=$'\t' read -r verb group skill; do
      files="$(printf '%s\n' "$map" | awk -F'\t' -v v="$verb" '$1==v{print $2}' |
        grep -Ev "$PLUMBING" | sed 's/.*/`&`/' | paste -sd, - | sed 's/,/, /g')"
      [ "$skill" = "-" ] && skill="" || skill="\`$skill\`"
      printf '| `%s` | %s | %s | %s |\n' "$verb" "$group" "$skill" "${files:-\`bin/cckit\` inline}"
    done
  cat <<'EOF'

Aliases resolve to a verb above; `cckit commands` lists them.
EOF
}

case "${1:-}" in
  --write) render >"$OUT" ;;
  --check)
    if ! render | diff -q - "$OUT" >/dev/null 2>&1; then
      printf 'x FEATURES.md is stale: run lib/core/feature-map.sh --write\n' >&2
      exit 1
    fi
    printf '  ok: FEATURES.md matches verbs.tsv and bin/cckit\n' >&2 ;;
  "") render ;;
  *) printf 'usage: feature-map.sh [--write|--check]\n' >&2; exit 2 ;;
esac
